//! What a theme becomes outside the Nyx apps. Each file is only rewritten when it
//! changes, and each thing that reads one is told only then.

use anyhow::{Context, Result};
use nyx_theme::Theme;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

fn home() -> PathBuf {
    PathBuf::from(std::env::var_os("HOME").unwrap_or_default())
}

fn xdg(var: &str, fallback: &str) -> PathBuf {
    std::env::var_os(var).map(PathBuf::from).filter(|p| p.is_absolute()).unwrap_or_else(|| home().join(fallback))
}

/// `rrggbb` from `#rgb`, `#rrggbb` or `#rrggbbaa`.
pub fn hex(colour: &str) -> Option<String> {
    let h = colour.trim().strip_prefix('#')?;
    if !h.bytes().all(|b| b.is_ascii_hexdigit()) {
        return None;
    }
    match h.len() {
        3 => Some(h.chars().flat_map(|c| [c, c]).collect()),
        6 | 8 => Some(h[..6].to_ascii_lowercase()),
        _ => None,
    }
}

fn swatch(theme: &Theme, name: &str, fallback: &str) -> String {
    theme
        .look
        .swatches
        .iter()
        .find(|(n, _)| n == name)
        .map(|(_, c)| c.as_str())
        .and_then(hex)
        .or_else(|| hex(fallback))
        .unwrap_or_else(|| "808080".into())
}

/// Write `text` to `path` if it differs; whether it did.
fn write_if_changed(path: &Path, text: &str) -> Result<bool> {
    if std::fs::read_to_string(path).is_ok_and(|t| t == text) {
        return Ok(false);
    }
    std::fs::create_dir_all(path.parent().context("no folder")?)?;
    let tmp = path.with_extension("nyx-themed");
    std::fs::write(&tmp, text)?;
    std::fs::rename(tmp, path)?;
    Ok(true)
}

pub fn hyprland_lua(theme: &Theme) -> String {
    let p = &theme.palette;
    let c = |colour: &str, fallback: &str| hex(colour).unwrap_or_else(|| fallback.into());
    format!(
        "-- Generated by nyx-themed for the {name} theme; it changes when the theme does.\n\
         hl.config({{\n  general = {{ col = {{ active_border = \"rgb({accent})\", inactive_border = \"rgb({border})\" }} }},\n  \
         misc = {{ background_color = \"rgb({bg})\" }},\n}})\n",
        name = theme.name,
        accent = c(&p.accent, "5b9cff"),
        border = c(&p.border, "2a2a2d"),
        bg = c(&p.bg, "09090a"),
    )
}

/// The lock screen's variables for hyprlock (`~/.config/hypr/nyx-hyprlock.conf`), from
/// the lock-screen theme and its wallpaper.
pub fn hyprlock_conf(theme: &Theme, wallpaper: Option<&Path>) -> String {
    let p = &theme.palette;
    let c = |colour: &str, fallback: &str| hex(colour).unwrap_or_else(|| fallback.into());
    format!(
        "# Generated by nyx-themed for the {name} lock-screen theme; it changes when the theme does.\n\
         $nyx_bg = rgb({bg})\n$nyx_surface = rgb({surface})\n$nyx_text = rgb({text})\n$nyx_dim = rgb({dim})\n\
         $nyx_accent = rgb({accent})\n$nyx_danger = rgb({danger})\n$nyx_wallpaper = {wallpaper}\n",
        name = theme.name,
        bg = c(&p.bg, "09090a"),
        surface = c(&p.surface, "161618"),
        text = c(&p.text, "e8e8ea"),
        dim = c(&p.dim_text, "8a8a90"),
        accent = c(&p.accent, "5b9cff"),
        danger = c(&p.danger, "ff5c5c"),
        wallpaper = wallpaper.map(|w| w.display().to_string()).unwrap_or_default(),
    )
}

pub fn foot_ini(theme: &Theme) -> String {
    let p = &theme.palette;
    let c = |colour: &str, fallback: &str| hex(colour).unwrap_or_else(|| fallback.into());
    let (bg, fg, surface, dim) = (c(&p.bg, "09090a"), c(&p.text, "e8e8ea"), c(&p.surface, "1a1a1c"), c(&p.dim_text, "9a9aa1"));
    let colours = [
        ("regular0", surface.clone()),
        ("regular1", swatch(theme, "red", &p.danger)),
        ("regular2", swatch(theme, "green", &theme.look.success)),
        ("regular3", swatch(theme, "amber", &theme.look.warning)),
        ("regular4", swatch(theme, "blue", &p.accent)),
        ("regular5", swatch(theme, "violet", &p.accent)),
        ("regular6", swatch(theme, "teal", &p.accent)),
        ("regular7", swatch(theme, "graphite", &p.dim_text)),
        ("bright0", dim.clone()),
        ("bright1", swatch(theme, "coral", &p.danger)),
        ("bright2", swatch(theme, "green", &theme.look.success)),
        ("bright3", swatch(theme, "amber", &theme.look.warning)),
        ("bright4", swatch(theme, "blue", &p.accent)),
        ("bright5", swatch(theme, "pink", &p.accent)),
        ("bright6", swatch(theme, "teal", &p.accent)),
        ("bright7", fg.clone()),
    ];
    let mut section = format!(
        "background={bg}\nforeground={fg}\nselection-background={}\nselection-foreground={fg}\ncursor={bg} {}\n",
        c(&p.border, "2a2a2d"),
        c(&p.accent, "5b9cff")
    );
    for (k, v) in colours {
        section.push_str(&format!("{k}={v}\n"));
    }
    // Foot picks colors-dark or colors-light; both are the theme.
    format!("# Generated by nyx-themed for the {} theme.\n[colors-dark]\n{section}\n[colors-light]\n{section}", theme.name)
}

/// The Hyprland instance this session runs, for hyprctl.
fn hyprland_instance() -> Option<String> {
    let dir = xdg("XDG_RUNTIME_DIR", "/nonexistent").join("hypr");
    std::fs::read_dir(dir)
        .ok()?
        .flatten()
        .find(|e| e.path().join(".socket.sock").exists())
        .map(|e| e.file_name().to_string_lossy().into())
}

fn quiet(cmd: &mut Command) -> Result<()> {
    let status = cmd.stdin(Stdio::null()).stdout(Stdio::null()).stderr(Stdio::null()).status()?;
    anyhow::ensure!(status.success(), "{status}");
    Ok(())
}

fn hyprland(theme: &Theme) -> Result<()> {
    let path = xdg("XDG_CONFIG_HOME", ".config").join("hypr/nyx-theme.lua");
    if write_if_changed(&path, &hyprland_lua(theme))?
        && let Some(instance) = hyprland_instance()
    {
        quiet(Command::new("hyprctl").arg("reload").env("HYPRLAND_INSTANCE_SIGNATURE", instance))?;
    }
    Ok(())
}

fn foot(theme: &Theme) -> Result<()> {
    write_if_changed(&xdg("XDG_CONFIG_HOME", ".config").join("foot/nyx-theme.ini"), &foot_ini(theme))?;
    Ok(())
}

fn gtk(theme: &Theme) -> Result<()> {
    let scheme = if theme.palette.light { "'prefer-light'" } else { "'prefer-dark'" };
    quiet(Command::new("dconf").args(["write", "/org/gnome/desktop/interface/color-scheme", scheme]))
}

/// The Nyx wallpapers' manifest.
fn wallpapers_manifest() -> PathBuf {
    std::env::var_os("NYX_WALLPAPERS")
        .map(PathBuf::from)
        .unwrap_or_else(|| "/run/current-system/sw/share/backgrounds/nyx/wallpapers.toml".into())
}

/// The user's own wallpaper, else the theme's default, else none.
pub fn wallpaper_for(theme_id: &str, appearance: &toml::Table, manifest: &Path) -> Option<PathBuf> {
    if let Some(own) = appearance.get("wallpaper").and_then(|v| v.as_str()).filter(|s| !s.is_empty()) {
        let own = own.strip_prefix("~/").map(|rest| home().join(rest)).unwrap_or_else(|| own.into());
        return Some(own);
    }
    let sets: toml::Table = std::fs::read_to_string(manifest).ok()?.parse().ok()?;
    let default = sets.get(theme_id).or_else(|| sets.get("nyx-dark"))?.get("default")?.as_str()?;
    Some(manifest.parent()?.join(default))
}

fn wallpaper(theme: &Theme, appearance: &toml::Table) -> Result<()> {
    let Some(path) = wallpaper_for(&theme.id, appearance, &wallpapers_manifest()) else { return Ok(()) };
    let state = xdg("XDG_STATE_HOME", ".local/state").join("nyx/wallpaper");
    if write_if_changed(&state, &format!("{}\n", path.display()))? {
        quiet(Command::new("systemctl").args(["--user", "try-restart", "nyx-wallpaper.service"]))?;
    }
    Ok(())
}

/// The lock screen's theme: `appearance.toml`'s `lock-theme`, else the desktop's.
fn lock_theme(theme: &Theme, appearance: &toml::Table) -> Theme {
    appearance
        .get("lock-theme")
        .and_then(|v| v.as_str())
        .and_then(|id| nyx_theme::all().into_iter().find(|t| t.id == nyx_theme::current_id(id)))
        .unwrap_or_else(|| theme.clone())
}

fn hyprlock(theme: &Theme, appearance: &toml::Table) -> Result<()> {
    let lock = lock_theme(theme, appearance);
    let wallpaper = wallpaper_for(&lock.id, appearance, &wallpapers_manifest());
    // hyprlock reads it each time it starts, so nothing has to be told.
    write_if_changed(
        &xdg("XDG_CONFIG_HOME", ".config").join("hypr/nyx-hyprlock.conf"),
        &hyprlock_conf(&lock, wallpaper.as_deref()),
    )?;
    Ok(())
}

pub fn write_all(theme: &Theme, appearance: &toml::Table) -> Vec<(&'static str, Result<()>)> {
    vec![
        ("Hyprland", hyprland(theme)),
        ("Foot", foot(theme)),
        ("GTK", gtk(theme)),
        ("wallpaper", wallpaper(theme, appearance)),
        ("lock screen", hyprlock(theme, appearance)),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn colours() {
        assert_eq!(hex("#5B9CFF").as_deref(), Some("5b9cff"));
        assert_eq!(hex("#abc").as_deref(), Some("aabbcc"));
        assert_eq!(hex("#11223344").as_deref(), Some("112233"));
        assert_eq!(hex("rgba(1,2,3)"), None);
    }

    #[test]
    fn theme_files() {
        let theme = nyx_theme::current_theme();
        let lua = hyprland_lua(&theme);
        assert!(lua.contains("active_border = \"rgb(") && lua.contains("background_color"));
        let lock = hyprlock_conf(&theme, Some(Path::new("/w/a.jpg")));
        assert!(lock.contains("$nyx_accent = rgb(") && lock.contains("$nyx_wallpaper = /w/a.jpg"));
        let ini = foot_ini(&theme);
        assert!(ini.contains("[colors-dark]") && ini.contains("regular4=") && ini.contains("bright7="));
    }

    #[test]
    fn wallpapers() {
        let d = tempfile::tempdir().unwrap();
        let manifest = d.path().join("wallpapers.toml");
        std::fs::write(&manifest, "[nyx-dark]\ndefault = \"nyx-dark/a.jpg\"\n").unwrap();
        let none = toml::Table::new();
        assert_eq!(wallpaper_for("nyx-dark", &none, &manifest), Some(d.path().join("nyx-dark/a.jpg")));
        assert_eq!(wallpaper_for("nord", &none, &manifest), Some(d.path().join("nyx-dark/a.jpg")));
        let own: toml::Table = "wallpaper = \"/srv/mine.png\"".parse().unwrap();
        assert_eq!(wallpaper_for("nord", &own, &manifest), Some(PathBuf::from("/srv/mine.png")));
    }
}
